//! The corpus test: real winget-pkgs manifests (`testdata/winget-corpus`,
//! a snapshot: THIRD_PARTY.md, WORKFLOW "Installing software") must all
//! read, and installer selection for a fixed set of machine profiles
//! must give the recorded answers (`testdata/winget-corpus/selected.txt`).
//!
//! Regenerate the golden file after a deliberate change of the rules:
//! `GALAPKG_BLESS=1 cargo test -p galapkg winget::corpus`, then review
//! its diff (every changed line is a package whose installer choice
//! moved).

use super::package::{Architecture, Package, Scope};
use super::select::{self, Choice, Machine, Request};
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::string::{String, ToString};
use std::vec::Vec;
use std::{format, println};

fn corpus_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("testdata/winget-corpus")
}

/// Every directory holding `.yaml` files, with its files (sorted).
fn version_dirs() -> BTreeMap<String, Vec<PathBuf>> {
    let root = corpus_root();
    let mut out: BTreeMap<String, Vec<PathBuf>> = BTreeMap::new();
    let mut stack = std::vec![root.join("manifests")];
    while let Some(dir) = stack.pop() {
        for e in fs::read_dir(&dir).unwrap() {
            let p = e.unwrap().path();
            if p.is_dir() {
                stack.push(p);
            } else if p.extension().is_some_and(|x| x == "yaml") {
                let rel = dir.strip_prefix(&root).unwrap().to_string_lossy().replace('\\', "/");
                out.entry(rel).or_default().push(p);
            }
        }
    }
    for files in out.values_mut() {
        files.sort();
    }
    out
}

fn read(files: &[PathBuf]) -> Result<Package, String> {
    let texts: Vec<(String, String)> = files
        .iter()
        .map(|p| {
            (p.file_name().unwrap().to_string_lossy().into_owned(), fs::read_to_string(p).unwrap())
        })
        .collect();
    let refs: Vec<(&str, &str)> = texts.iter().map(|(n, t)| (n.as_str(), t.as_str())).collect();
    Package::from_files(&refs).map_err(|e| e.to_string())
}

/// The fixed profiles: architecture, preferred scope, locale.
fn profiles() -> Vec<(String, Machine, Request)> {
    let mut out = Vec::new();
    for arch in [Architecture::X64, Architecture::Arm64] {
        for scope in [Scope::User, Scope::Machine] {
            for locale in ["en-US", "de-DE"] {
                let name = format!("{}/{}/{locale}", arch.as_str(), scope.as_str());
                let request =
                    Request { scope: Choice::prefer(std::vec![scope]), ..Request::default() };
                out.push((name, Machine::gala(arch, locale), request));
            }
        }
    }
    out
}

fn golden_text(dirs: &BTreeMap<String, Vec<PathBuf>>) -> (String, usize, usize) {
    let profiles = profiles();
    let mut text = String::from(
        "# Installer selection over testdata/winget-corpus for fixed machine profiles\n# (architecture/preferred scope/locale). Generated by\n# `GALAPKG_BLESS=1 cargo test -p galapkg winget::corpus`; do not edit.\n# Tab-separated: <version directory> <profile> <installer number> <InstallerUrl>\n# <effective installer type> <arguments in winget's default mode>, or\n# <version directory> <profile> none: <reasons>\n",
    );
    let mut selected = 0;
    let mut none = 0;
    for (dir, files) in dirs {
        let Ok(p) = read(files) else { continue };
        for (name, machine, request) in &profiles {
            let line = match select::select(&p, machine, request) {
                Ok(s) => {
                    selected += 1;
                    let i = s.installer;
                    let ty = i.effective_type().map_or("?", |t| t.as_str());
                    let args = select::command_line(i, &select::CommandOptions::default())
                        .unwrap_or_else(|e| format!("({e})"));
                    format!("{dir}\t{name}\t{}\t{}\t{ty}\t{args}\n", i.index + 1, i.url)
                }
                Err(e) => {
                    none += 1;
                    format!("{dir}\t{name}\tnone: {e}\n")
                }
            };
            text.push_str(&line);
        }
    }
    (text, selected, none)
}

#[test]
fn corpus_parses_and_selection_matches_golden() {
    let dirs = version_dirs();
    assert!(dirs.len() >= 300, "the corpus has {} version directories", dirs.len());
    let mut failures = Vec::new();
    let mut warnings = 0;
    let mut schemas: BTreeMap<String, usize> = BTreeMap::new();
    let mut multi = 0;
    for (dir, files) in &dirs {
        match read(files) {
            Ok(p) => {
                warnings += p.warnings.len();
                for w in &p.warnings {
                    println!("corpus warning: {dir}/{w}");
                }
                *schemas.entry(p.manifest_version.clone()).or_default() += 1;
                if p.form == super::package::Form::MultiFile {
                    multi += 1;
                }
                // Every package is readable twice the same way.
                assert_eq!(read(files).unwrap(), p, "{dir}");
            }
            Err(e) => failures.push(format!("{dir}: {e}")),
        }
    }
    println!(
        "corpus: {} version directories ({multi} multi-file), {warnings} warnings, schemas {schemas:?}",
        dirs.len()
    );
    assert!(
        failures.is_empty(),
        "{} manifests did not read:\n{}",
        failures.len(),
        failures.join("\n")
    );

    let (text, selected, none) = golden_text(&dirs);
    // Deterministic: the same answer again.
    assert_eq!(golden_text(&dirs).0, text);
    println!("corpus: {selected} selections, {none} with no applicable installer");
    let golden = corpus_root().join("selected.txt");
    if std::env::var_os("GALAPKG_BLESS").is_some() {
        fs::write(&golden, &text).unwrap();
        return;
    }
    let want = fs::read_to_string(&golden).unwrap_or_default();
    if want != text {
        let diff: Vec<String> = want
            .lines()
            .zip(text.lines())
            .filter(|(a, b)| a != b)
            .take(20)
            .map(|(a, b)| format!("- {a}\n+ {b}"))
            .collect();
        panic!(
            "selection differs from {} ({} vs {} lines); first differences:\n{}\n(GALAPKG_BLESS=1 regenerates it)",
            golden.display(),
            want.lines().count(),
            text.lines().count(),
            diff.join("\n")
        );
    }
}

/// Damaged manifests (cut short anywhere, a line's start replaced by a
/// YAML indicator) give errors, never a panic: manifests come from the
/// network.
#[test]
fn damaged_manifests_do_not_panic() {
    let dirs = version_dirs();
    let mut checked = 0;
    for files in dirs.values().step_by(20) {
        for path in files {
            let text = fs::read_to_string(path).unwrap();
            let bounds: Vec<usize> = text.char_indices().map(|(i, _)| i).step_by(5).collect();
            for &cut in &bounds {
                let _ = super::yaml::parse(&text[..cut]);
                let _ = Package::from_texts(&[&text[..cut]]);
                checked += 1;
            }
            let lines: Vec<&str> = text.lines().collect();
            for n in 0..lines.len() {
                for bad in [
                    "- ", ": ", "[", "{", "\"", "'", "|", ">", "#", "\t", " ", "? ", "&a ", "*a",
                    "\\",
                ] {
                    let mut damaged = String::new();
                    for (k, l) in lines.iter().enumerate() {
                        if k == n {
                            damaged.push_str(bad);
                        }
                        damaged.push_str(l);
                        damaged.push('\n');
                    }
                    let _ = Package::from_texts(&[&damaged]);
                    checked += 1;
                }
            }
        }
    }
    println!("damaged: {checked} variants read without a panic");
}

#[test]
fn corpus_warnings_are_positioned() {
    // Every warning names a file and a real position.
    for files in version_dirs().values() {
        if let Ok(p) = read(files) {
            for w in &p.warnings {
                assert!(!w.file.is_empty() && w.at.line > 0 && w.at.col > 0, "{w}");
            }
        }
    }
}
