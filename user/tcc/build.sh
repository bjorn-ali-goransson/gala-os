#!/bin/sh
# Builds user/bin/tcc.tar: TinyCC (a small C compiler, assembler and
# linker) for x64 Windows, as an installation tree for the `tcc` scenario
# (ROADMAP H4):
#   tcc/tcc.exe      tcc.c compiled in one unit with mingw-w64 (no
#                    configure step: config.h is written here)
#   tcc/include/     tcc's own headers and its win32 C library headers
#   tcc/lib/*.def    import definitions (kernel32, msvcrt, ...)
#   tcc/src/         the sources of libtcc1.a and the startup code, which
#                    the scenario compiles on gala with this tcc.exe
# Reproducible: a pinned commit, no debug info, no link timestamp, a tar
# with sorted names, fixed times and owners. Needs x86_64-w64-mingw32-gcc
# (Ubuntu: gcc-mingw-w64-x86-64), git and GNU tar. Without them, keep
# using the checked-in user/bin/tcc.tar.
#
# TinyCC is LGPL-2.1 (THIRD_PARTY.md): the source is the pinned commit of
# https://repo.or.cz/tinycc.git (branch mob).
set -eu

COMMIT=e23dabed154a8495f3ac1ff3cc9d04fa1c207893
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
WORK=/tmp/gala-tcc-build

rm -rf "$WORK"
git clone -q https://repo.or.cz/tinycc.git "$WORK"
cd "$WORK"
git checkout -q "$COMMIT"

# What configure would write, for this build.
printf '#define TCC_VERSION "%s"\n#define TCC_GITHASH "mob:%s"\n' \
    "$(cat VERSION)" "$(echo "$COMMIT" | cut -c1-7)" > config.h
# CONFIG_TCC_PREDEFS=0: tcc reads include/tccdefs.h at run time instead
# of a table generated by running a host-built tool.
x86_64-w64-mingw32-gcc -O2 -g0 -s -Wl,--no-insert-timestamp \
    -DTCC_TARGET_PE -DTCC_TARGET_X86_64 -DONE_SOURCE=1 -DCONFIG_TCC_PREDEFS=0 \
    -o tcc.exe tcc.c

T=$WORK/out/tcc
mkdir -p "$T/include" "$T/lib" "$T/src"
cp tcc.exe "$T/"
cp -r include/. win32/include/. "$T/include/"
cp win32/lib/*.def "$T/lib/"
cp win32/lib/crt1.c win32/lib/crt1w.c win32/lib/wincrt1.c win32/lib/wincrt1w.c \
    win32/lib/dllcrt1.c win32/lib/dllmain.c win32/lib/winex.c win32/lib/crtinit.c \
    win32/lib/chkstk.S lib/libtcc1.c lib/alloca.S lib/alloca-bt.S \
    lib/stdatomic.c lib/atomic.S lib/builtin.c "$T/src/"
cp COPYING "$T/"
tar -C "$WORK/out" --sort=name --mtime=@1700000000 --owner=0 --group=0 \
    --numeric-owner --format=ustar -cf "$ROOT/user/bin/tcc.tar" tcc
sha256sum "$ROOT/user/bin/tcc.tar"
