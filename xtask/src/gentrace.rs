//! `cargo xtask gen-trace`: a wrapper per vtable slot, generated.
//!
//! A program's call into one of gala's DLLs is an indirect call through a
//! vtable in the program's own address space: the kernel never sees it, so
//! the only place that can record it is the DLL. Records written by hand
//! leave one gap -- the method nobody instrumented -- and that gap is
//! invisible, so the wrappers are generated from the slot lists instead.
//! Every function a vtable points at gets one; it records the first call
//! that reaches the method (ROADMAP OT3b, OBSERVABILITY "Missing-features
//! ledger") and then calls it. The slot list is rewritten to point at the
//! wrapper, so a method added to a vtable is traced by having been added.
//!
//! A method's name comes from the function's own: `t_CreateBitmap` in a
//! file that maps the prefix `t_` to ID2D1RenderTarget is
//! ID2D1RenderTarget::CreateBitmap. The maps are directives beside the
//! slot lists they describe, so the DLL names its own interfaces:
//!
//! ```text
//! // gen-trace prefix t_ ID2D1RenderTarget
//! // gen-trace fn get_factory ID2D1Resource::GetFactory
//! // gen-trace skip some_helper
//! ```
//!
//! A slot whose name no directive explains is an error, not a silence, so
//! a new interface cannot be left unnamed. IUnknown's three methods are
//! never wrapped: every program calls them on every object and they say
//! nothing about what it is trying to do.
//!
//! The generated block is checked in and CI runs the generator again to
//! see it unchanged, as it does for the test binaries in `user/bin`
//! (WORKFLOW "Generated code").

use crate::Result;
use proc_macro2::LineColumn;
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use syn::spanned::Spanned;

/// Where the generated block starts; everything from there to the end of
/// the file is the generator's.
const MARK: &str = "// ==== generated by `cargo xtask gen-trace`: do not edit ====";

/// The DLLs whose vtable slots are traced. dwrite's functions are named in
/// snake_case, so its names cannot be derived from a prefix; it joins when
/// they follow d2d1's `<prefix>_<Method>` convention (ROADMAP OT3b).
const DLLS: &[&str] = &["user/d2d1/src"];

/// IUnknown's three, by the names this code gives them. Every program
/// calls them on every object, so a record of one tells us nothing.
fn is_plumbing(name: &str) -> bool {
    const TAILS: &[&str] = &["_query", "_release", "_add_ref", "_query_fn", "_release_fn", "_qi"];
    name == "add_ref" || TAILS.iter().any(|t| name.ends_with(t))
}

/// One function a vtable points at.
struct Slot {
    /// Its signature as written, `extern "system" fn ...` without a `pub`.
    sig: String,
    /// Its parameters' names, in order, to pass on.
    args: Vec<String>,
}

/// What a file says about its own names (its `// gen-trace` directives).
#[derive(Default)]
struct Names {
    /// A function-name prefix and the interface its methods belong to.
    prefixes: Vec<(String, String)>,
    /// A function's full `Interface::Method`, where no prefix gives it.
    fns: BTreeMap<String, String>,
    /// Functions deliberately left untraced; the comment says why.
    skip: BTreeSet<String>,
}

impl Names {
    /// The `Interface::Method` of a function, by its own name.
    fn of(&self, f: &str) -> Option<String> {
        if let Some(n) = self.fns.get(f) {
            return Some(n.clone());
        }
        // The longest matching prefix, so `dc1_` wins over `dc_`.
        let mut best: Option<(&str, &str)> = None;
        for (p, iface) in &self.prefixes {
            if f.starts_with(p.as_str()) && best.is_none_or(|(b, _)| p.len() > b.len()) {
                best = Some((p, iface));
            }
        }
        let (p, iface) = best?;
        Some(format!("{iface}::{}", &f[p.len()..]))
    }
}

/// A file read for generation: its source without the generated block.
struct Source {
    path: PathBuf,
    /// The module's name (the file stem), `lib` for the crate root.
    module: String,
    text: String,
    names: Names,
    defs: BTreeMap<String, Slot>,
}

/// The `// gen-trace ...` directives, wherever they are in the file.
fn read_names(text: &str) -> Result<Names> {
    let mut names = Names::default();
    for line in text.lines() {
        let Some(rest) = line.trim_start().strip_prefix("// gen-trace ") else { continue };
        let words: Vec<&str> = rest.split_whitespace().collect();
        match words.as_slice() {
            ["prefix", p, iface] => names.prefixes.push(((*p).to_string(), (*iface).to_string())),
            ["fn", f, full] => {
                names.fns.insert((*f).to_string(), (*full).to_string());
            }
            ["skip", f] => {
                names.skip.insert((*f).to_string());
            }
            _ => return Err(format!("gen-trace: directive not understood: {line}")),
        }
    }
    Ok(names)
}

/// The byte offset of a character column (spans count characters).
fn char_byte(line: &str, col: usize) -> usize {
    line.char_indices().nth(col).map_or(line.len(), |(i, _)| i)
}

/// The text of `lines` between two positions (a span's start and end).
fn slice(lines: &[&str], s: LineColumn, e: LineColumn) -> String {
    if s.line == e.line {
        let l = lines[s.line - 1];
        return l[char_byte(l, s.column)..char_byte(l, e.column)].to_string();
    }
    let mut out = String::new();
    for n in s.line..=e.line {
        let l = lines[n - 1];
        if n == s.line {
            out.push_str(&l[char_byte(l, s.column)..]);
        } else if n == e.line {
            out.push('\n');
            out.push_str(&l[..char_byte(l, e.column)]);
        } else {
            out.push('\n');
            out.push_str(l);
        }
    }
    out
}

/// Every `extern "system" fn` the file defines at its top level.
fn read_defs(path: &Path, text: &str) -> Result<BTreeMap<String, Slot>> {
    let file = syn::parse_file(text).map_err(|e| format!("gen-trace: {}: {e}", path.display()))?;
    let lines: Vec<&str> = text.lines().collect();
    let mut defs = BTreeMap::new();
    for item in &file.items {
        let syn::Item::Fn(f) = item else { continue };
        let Some(abi) = &f.sig.abi else { continue };
        if !abi.name.as_ref().is_some_and(|n| n.value() == "system") {
            continue;
        }
        let mut args = Vec::new();
        for arg in &f.sig.inputs {
            let syn::FnArg::Typed(t) = arg else {
                return Err(format!("gen-trace: {}: {} takes self", path.display(), f.sig.ident));
            };
            let syn::Pat::Ident(id) = &*t.pat else {
                return Err(format!(
                    "gen-trace: {}: a parameter of {} is not a name",
                    path.display(),
                    f.sig.ident
                ));
            };
            args.push(id.ident.to_string());
        }
        let span = f.sig.span();
        defs.insert(
            f.sig.ident.to_string(),
            Slot { sig: slice(&lines, span.start(), span.end()), args },
        );
    }
    Ok(defs)
}

/// Every `<path> as *const ()` in the file: where it is and what it names.
fn slot_refs(text: &str) -> Vec<(usize, usize, String)> {
    const TAIL: &str = " as *const ()";
    let bytes = text.as_bytes();
    let mut out = Vec::new();
    let mut at = 0;
    while let Some(i) = text[at..].find(TAIL) {
        let end = at + i;
        at = end + TAIL.len();
        let mut start = end;
        while start > 0 {
            let c = bytes[start - 1];
            if c.is_ascii_alphanumeric() || c == b'_' || c == b':' {
                start -= 1;
            } else {
                break;
            }
        }
        // `$extra as *const ()` is a macro's own parameter, not a slot:
        // the names it stands for are read at the invocations instead.
        if start < end && !(start > 0 && bytes[start - 1] == b'$') {
            out.push((start, end, text[start..end].to_string()));
        }
    }
    out
}

/// The spans of the `<name>_slots!( ... )` invocations, whose arguments are
/// bare function names the macro turns into slots of its own.
fn slot_macro_args(text: &str) -> Vec<(usize, usize)> {
    let bytes = text.as_bytes();
    let mut out = Vec::new();
    let mut at = 0;
    while let Some(i) = text[at..].find("_slots!(") {
        let open = at + i + "_slots!(".len();
        at = open;
        let mut depth = 1usize;
        let mut j = open;
        while j < bytes.len() && depth > 0 {
            match bytes[j] {
                b'(' => depth += 1,
                b')' => depth -= 1,
                _ => {}
            }
            j += 1;
        }
        if depth == 0 {
            out.push((open, j - 1));
        }
    }
    out
}

/// The paths of a piece of source, in order, with their spans: a whole
/// `crate::target::traced::f_X`, not its segments.
fn path_spans(text: &str) -> Vec<(usize, usize, String)> {
    let b = text.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < b.len() {
        if b[i].is_ascii_alphabetic() || b[i] == b'_' {
            let s = i;
            while i < b.len() && (b[i].is_ascii_alphanumeric() || b[i] == b'_') {
                i += 1;
            }
            while i + 2 < b.len()
                && &text[i..i + 2] == "::"
                && (b[i + 2].is_ascii_alphabetic() || b[i + 2] == b'_')
            {
                i += 2;
                while i < b.len() && (b[i].is_ascii_alphanumeric() || b[i] == b'_') {
                    i += 1;
                }
            }
            out.push((s, i, text[s..i].to_string()));
        } else {
            i += 1;
        }
    }
    out
}

/// The wrapper of one slot: the record, then the method. It is as visible
/// as its slot lists need and no more, so a wrapper of a method whose
/// arguments are this module's own types is not a more public item than
/// the types it takes.
fn wrapper(f: &str, slot: &Slot, name: &str, elsewhere: bool) -> String {
    let vis = if elsewhere { "pub(crate)" } else { "pub(super)" };
    format!(
        "/// {name}, traced.\n{sig} {{\ncrate::traced!(b\"{name}\", [{args}]);\nsuper::{f}({args})\n}}\n",
        sig = slot.sig.replacen("extern", &format!("{vis} extern"), 1),
        args = slot.args.join(", "),
    )
}

/// `rustfmt` over a whole file's text, with the workspace's rustfmt.toml.
fn format(root: &Path, text: &str) -> Result<String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout", "--quiet"])
        .current_dir(root)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .map_err(|e| format!("gen-trace: rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .ok_or("gen-trace: rustfmt took no input")?
        .write_all(text.as_bytes())
        .map_err(|e| format!("gen-trace: rustfmt: {e}"))?;
    let out = child.wait_with_output().map_err(|e| format!("gen-trace: rustfmt: {e}"))?;
    if !out.status.success() {
        return Err("gen-trace: rustfmt rejected the generated code".into());
    }
    String::from_utf8(out.stdout).map_err(|e| format!("gen-trace: rustfmt: {e}"))
}

/// Who owns a slot reference: the module that defines the function, and
/// the function's name. A bare name is this module's or the crate root's,
/// and a `traced` segment is one the generator put there itself, so
/// reading its own output gives the same answer as reading the source it
/// started from.
fn owner_of(src: &Source, path: &str) -> (String, String) {
    let mut segs: Vec<&str> = path.split("::").collect();
    let f = segs.pop().unwrap_or_default().to_string();
    if segs.last() == Some(&"traced") {
        segs.pop();
    }
    let owner = match segs.last() {
        None if src.defs.contains_key(&f) => src.module.clone(),
        None | Some(&"crate") => "lib".to_string(),
        Some(m) => (*m).to_string(),
    };
    (owner, f)
}

/// How this file must name a slot of `owner` so the wrapper is called.
fn slot_path(src: &Source, owner: &str, f: &str) -> String {
    if owner == src.module {
        format!("traced::{f}")
    } else if owner == "lib" {
        format!("crate::traced::{f}")
    } else {
        format!("crate::{owner}::traced::{f}")
    }
}

/// Generate the wrappers of every DLL in `DLLS` and point its slot lists
/// at them, writing only the files that change.
pub fn gen_trace(root: &Path) -> Result {
    let mut written = 0;
    for dll in DLLS {
        written += one_dll(root, &root.join(dll))?;
    }
    println!("xtask: gen-trace: {written} file(s) written");
    Ok(())
}

fn one_dll(root: &Path, dir: &Path) -> Result<usize> {
    // Read every module, each without whatever the generator left there.
    let mut paths: Vec<PathBuf> = fs::read_dir(dir)
        .map_err(|e| format!("gen-trace: {}: {e}", dir.display()))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "rs"))
        .collect();
    paths.sort();
    let mut sources = Vec::new();
    for path in paths {
        let whole = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let text = match whole.find(MARK) {
            Some(i) => whole[..i].trim_end().to_string() + "\n",
            None => whole,
        };
        let module = path.file_stem().unwrap_or_default().to_string_lossy().to_string();
        let names = read_names(&text)?;
        let defs = read_defs(&path, &text)?;
        sources.push(Source { path, module, text, names, defs });
    }

    // Which functions a vtable points at, by the module that defines them.
    let mut traced: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut elsewhere: BTreeSet<(String, String)> = BTreeSet::new();
    for src in &sources {
        for (_, _, path) in slot_refs(&src.text) {
            let (owner, f) = owner_of(src, &path);
            if is_plumbing(&f) {
                continue;
            }
            let Some(home) = sources.iter().find(|s| s.module == owner) else {
                return Err(format!(
                    "gen-trace: {}: slot {path} names a module this DLL has not got",
                    src.path.display()
                ));
            };
            if !home.defs.contains_key(&f) {
                return Err(format!(
                    "gen-trace: {}: slot {path} is not defined in {owner}.rs",
                    src.path.display()
                ));
            }
            if home.names.skip.contains(&f) {
                continue;
            }
            if owner != src.module {
                elsewhere.insert((owner.clone(), f.clone()));
            }
            traced.entry(owner).or_default().insert(f);
        }
        // The names a slot macro is handed as arguments, which it turns
        // into slots of its own.
        for (a, b) in slot_macro_args(&src.text) {
            for (_, _, path) in path_spans(&src.text[a..b]) {
                let (owner, f) = owner_of(src, &path);
                if owner == src.module
                    && src.defs.contains_key(&f)
                    && !is_plumbing(&f)
                    && !src.names.skip.contains(&f)
                {
                    traced.entry(src.module.clone()).or_default().insert(f);
                }
            }
        }
    }

    // Every traced function needs a name, and a nameless one is an error.
    let mut named: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    for (module, fns) in &traced {
        let src = sources.iter().find(|s| &s.module == module).ok_or("gen-trace: lost module")?;
        for f in fns {
            let name = src.names.of(f).ok_or_else(|| {
                format!(
                    "gen-trace: {}: no directive names {f}; add `// gen-trace prefix <p> \
                     <Interface>`, `// gen-trace fn {f} <Interface>::<Method>` or \
                     `// gen-trace skip {f}`",
                    src.path.display()
                )
            })?;
            named.entry(module.clone()).or_default().insert(f.clone(), name);
        }
    }

    // Point the slot lists at the wrappers, then append the wrappers.
    let mut written = 0;
    for src in &sources {
        let mut edits: Vec<(usize, usize, String)> = Vec::new();
        for (a, b, path) in slot_refs(&src.text) {
            let (owner, f) = owner_of(src, &path);
            if named.get(&owner).is_some_and(|m| m.contains_key(&f)) {
                edits.push((a, b, slot_path(src, &owner, &f)));
            }
        }
        for (a, b) in slot_macro_args(&src.text) {
            for (s, e, path) in path_spans(&src.text[a..b]) {
                let (owner, f) = owner_of(src, &path);
                if owner == src.module && named.get(&owner).is_some_and(|m| m.contains_key(&f)) {
                    edits.push((a + s, a + e, slot_path(src, &owner, &f)));
                }
            }
        }
        edits.sort_by_key(|(a, _, _)| *a);
        let mut body = String::new();
        let mut at = 0;
        for (a, b, with) in edits {
            if a < at {
                continue;
            }
            body.push_str(&src.text[at..a]);
            body.push_str(&with);
            at = b;
        }
        body.push_str(&src.text[at..]);

        if let Some(fns) = named.get(&src.module) {
            body.push('\n');
            body.push_str(MARK);
            body.push_str(
                "\n/// The wrapper of every vtable slot of this module: each records\n\
                 /// the first call that reaches its method, and every call at all\n\
                 /// once `trace_from=` has armed one (`cargo xtask gen-trace`).\n\
                 pub(crate) mod traced {\nuse super::*;\n",
            );
            for (f, name) in fns {
                let out = elsewhere.contains(&(src.module.clone(), f.clone()));
                body.push_str(&wrapper(f, &src.defs[f], name, out));
            }
            body.push_str("}\n");
        }
        let text = format(root, &body)?;
        if text != fs::read_to_string(&src.path).unwrap_or_default() {
            fs::write(&src.path, &text).map_err(|e| format!("{}: {e}", src.path.display()))?;
            written += 1;
        }
    }
    Ok(written)
}
